func TestPerturbUndoByteIdentical(t *testing.T) {
	nonce := "test-nonce-12345"

	tests := []struct {
		name string
		path string
		data []byte
	}{
		{
			name: "Go file with newline",
			path: "pkg/foo.go",
			data: []byte("package pkg\n\nfunc Foo() {}\n"),
		},
		{
			name: "Go file without trailing newline",
			path: "pkg/foo.go",
			data: []byte("package pkg\n\nfunc Foo() {}"),
		},
		{
			name: "YAML file",
			path: "config.yaml",
			data: []byte("apiVersion: v1\nkind: Config\n"),
		},
		{
			name: "Shell script",
			path: "script.sh",
			data: []byte("#!/bin/bash\necho hello\n"),
		},
		{
			name: "Markdown file",
			path: "README.md",
			data: []byte("# Title\nSome content\n"),
		},
		{
			name: "SQL file",
			path: "schema.sql",
			data: []byte("CREATE TABLE users (id INT);\n"),
		},
		{
			name: "Binary file non-empty",
			path: "data.bin",
			data: []byte{0x00, 0xFF, 0x12, 0x34, 0x56},
		},
		{
			name: "Binary file empty",
			path: "empty.bin",
			data: []byte{},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			perturbed, marker, isBinary, wasEmpty := Perturb(tt.path, tt.data, nonce)

			if len(tt.data) > 0 && bytes.Equal(perturbed, tt.data) {
				t.Fatalf("perturbed content must differ from original")
			}

			undone, ok := Undo(perturbed, marker, isBinary, wasEmpty)
			if !ok {
				t.Fatalf("Undo returned false")
			}
			if !bytes.Equal(undone, tt.data) {
				t.Fatalf("Undo failed to restore exact bytes:\nGot:  %v (%q)\nWant: %v (%q)", undone, string(undone), tt.data, string(tt.data))
			}
		})
	}
}

func TestFindGeneratedFiles(t *testing.T) {
	root := t.TempDir()

	apDir := filepath.Join(root, ".ap")
	if err := os.MkdirAll(apDir, 0755); err != nil {
		t.Fatal(err)
	}
	apYAML := `
generate:
  ignoreOrphans:
    - "ignored/*.go"
`
	if err := os.WriteFile(filepath.Join(apDir, "ap.yaml"), []byte(apYAML), 0644); err != nil {
		t.Fatal(err)
	}

	// 1. Detected by Go generated header
	genGoPath := filepath.Join(root, "service.pb.go")
	if err := os.WriteFile(genGoPath, []byte("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage p\n"), 0644); err != nil {
		t.Fatal(err)
	}

	// 2. Detected by shell generated header
	genShPath := filepath.Join(root, "script.sh")
	if err := os.WriteFile(genShPath, []byte("#!/bin/bash\n# Code generated by ap generate. DO NOT EDIT.\necho 1\n"), 0755); err != nil {
		t.Fatal(err)
	}

	// 3. File without generated header (even if named *.pb.go or zz_generated*)
	unmarkedPbPath := filepath.Join(root, "unmarked.pb.go")
	if err := os.WriteFile(unmarkedPbPath, []byte("package p\n"), 0644); err != nil {
		t.Fatal(err)
	}

	unmarkedZzPath := filepath.Join(root, "zz_generated.deepcopy.go")
	if err := os.WriteFile(unmarkedZzPath, []byte("package p\n"), 0644); err != nil {
		t.Fatal(err)
	}

	// 4. Normal handwritten file (not generated)
	normPath := filepath.Join(root, "normal.go")
	if err := os.WriteFile(normPath, []byte("package p\nfunc Run() {}\n"), 0644); err != nil {
		t.Fatal(err)
	}

	// 5. Ignored generated file
	ignoredDir := filepath.Join(root, "ignored")
	if err := os.MkdirAll(ignoredDir, 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(ignoredDir, "skip.go"), []byte("// Code generated by tool. DO NOT EDIT.\npackage p\n"), 0644); err != nil {
		t.Fatal(err)
	}

	// 6. Testdata file (should be skipped)
	testdataDir := filepath.Join(root, "pkg", "testdata")
	if err := os.MkdirAll(testdataDir, 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(testdataDir, "fake.pb.go"), []byte("// Code generated by tool. DO NOT EDIT.\npackage p\n"), 0644); err != nil {
		t.Fatal(err)
	}

	// 7. Test file (should be skipped)
	if err := os.WriteFile(filepath.Join(root, "foo_test.go"), []byte("// Code generated by test. DO NOT EDIT.\npackage p\n"), 0644); err != nil {
		t.Fatal(err)
	}

	r, err := repo.Open(root)
	if err != nil {
		t.Fatal(err)
	}
	scope := &tasks.APScope{RepoRoot: root, Dir: root, Repo: r}

	files, err := FindGeneratedFiles(root, []*tasks.APScope{scope})
	if err != nil {
		t.Fatalf("FindGeneratedFiles failed: %v", err)
	}

	foundPaths := make(map[string]bool)
	for _, f := range files {
		foundPaths[f.Path] = true
	}

	if !foundPaths[genGoPath] {
		t.Errorf("expected service.pb.go with header to be detected as generated")
	}
	if !foundPaths[genShPath] {
		t.Errorf("expected script.sh with header to be detected as generated")
	}
	if foundPaths[unmarkedPbPath] {
		t.Errorf("unmarked.pb.go without header should not be detected as generated")
	}
	if foundPaths[unmarkedZzPath] {
		t.Errorf("zz_generated without header should not be detected as generated")
	}
	if foundPaths[normPath] {
		t.Errorf("normal.go should not be detected as generated")
	}
	if foundPaths[filepath.Join(ignoredDir, "skip.go")] {
		t.Errorf("ignored file should be skipped")
	}
	if foundPaths[filepath.Join(testdataDir, "fake.pb.go")] {
		t.Errorf("testdata file should be skipped")
	}
	if foundPaths[filepath.Join(root, "foo_test.go")] {
		t.Errorf("test file should be skipped")
	}
}

func TestRunVerify_SuccessAndMtimePreservation(t *testing.T) {
	ctx := t.Context()
	root := t.TempDir()

	writeTestHeadersConfig(t, root)

	initialContent := "#!/bin/bash\n# Code generated by ap generate. DO NOT EDIT.\necho test\n"
	targetFile := filepath.Join(root, "script.sh")
	if err := os.WriteFile(targetFile, []byte(initialContent), 0755); err != nil {
		t.Fatal(err)
	}

	oldTime := time.Now().Add(-1 * time.Hour).Truncate(time.Second)
	if err := os.Chtimes(targetFile, oldTime, oldTime); err != nil {
		t.Fatal(err)
	}

	r, err := repo.Open(root)
	if err != nil {
		t.Fatal(err)
	}
	scope := &tasks.APScope{RepoRoot: root, Dir: root, Repo: r}

	genTask := &tasks.DummyTask{
		Name: "ap-test",
		RunFn: func(_ context.Context, _ *tasks.APScope) error {
			return os.WriteFile(targetFile, []byte(initialContent), 0755)
		},
	}

	err = RunVerify(ctx, root, []*tasks.APScope{scope}, []tasks.Task{genTask}, false)
	if err != nil {
		t.Fatalf("RunVerify failed unexpectedly: %v", err)
	}

	data, err := os.ReadFile(targetFile)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(data, []byte(initialContent)) {
		t.Errorf("expected restored content, got %q", string(data))
	}

	fi, err := os.Stat(targetFile)
	if err != nil {
		t.Fatal(err)
	}
	if !fi.ModTime().Equal(oldTime) {
		t.Errorf("mtime was not preserved: got %v, want %v", fi.ModTime(), oldTime)
	}
}

func TestRunVerify_UnrestoredMarkerDetected(t *testing.T) {
	ctx := t.Context()
	root := t.TempDir()

	writeTestHeadersConfig(t, root)

	initialContent := "#!/bin/bash\n# Code generated by ap generate. DO NOT EDIT.\necho test\n"
	targetFile := filepath.Join(root, "script.sh")
	if err := os.WriteFile(targetFile, []byte(initialContent), 0755); err != nil {
		t.Fatal(err)
	}

	r, err := repo.Open(root)
	if err != nil {
		t.Fatal(err)
	}
	scope := &tasks.APScope{RepoRoot: root, Dir: root, Repo: r}

	noopTask := &tasks.DummyTask{
		Name: "ap-test",
		RunFn: func(_ context.Context, _ *tasks.APScope) error {
			return nil
		},
	}

	err = RunVerify(ctx, root, []*tasks.APScope{scope}, []tasks.Task{noopTask}, false)
	if err == nil {
		t.Fatalf("expected RunVerify to fail on unrestored marker")
	}
	if !strings.Contains(err.Error(), "still carries perturbation marker") {
		t.Errorf("expected error to mention perturbation marker, got %v", err)
	}

	// Verify defer restored the file via Undo so no marker remains
	data, err := os.ReadFile(targetFile)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(data, []byte(initialContent)) {
		t.Errorf("cleanup did not restore original content; got %q", string(data))
	}
}

