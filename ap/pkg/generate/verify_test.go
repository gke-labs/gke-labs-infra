func TestRunVerify_V1Format_Success(t *testing.T) {
	ctx := t.Context()
	root := t.TempDir()

	writeTestHeadersConfig(t, root)

	if err := os.WriteFile(filepath.Join(root, ".ap", "ap.yaml"), []byte("generatedHeader: v1\n"), 0644); err != nil {
		t.Fatal(err)
	}

	presubmitsDir := filepath.Join(root, "dev", "ci", "presubmits")
	if err := os.MkdirAll(presubmitsDir, 0755); err != nil {
		t.Fatal(err)
	}

	// 1. Initial v1 ap-test generation
	if err := runApTestGenerator(ctx, root); err != nil {
		t.Fatal(err)
	}
	v1TestContent, err := os.ReadFile(filepath.Join(presubmitsDir, "ap-test"))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(v1TestContent), "Code generated by ap generate") {
		t.Fatalf("expected v1 format for ap-test, got: %s", string(v1TestContent))
	}

	// 2. Initial v1 workflow generation
	r, err := repo.Open(root)
	if err != nil {
		t.Fatal(err)
	}
	scope := &tasks.APScope{RepoRoot: root, Dir: root, Repo: r}
	if err := runGithubActionsGenerator(ctx, root, []*tasks.APScope{scope}); err != nil {
		t.Fatal(err)
	}

	repo.ResetCache()
	r, err = repo.Open(root)
	if err != nil {
		t.Fatal(err)
	}
	scope = &tasks.APScope{RepoRoot: root, Dir: root, Repo: r}

	// Verify that unmarked v1 scripts are not included in generated files, but marked workflow is
	genFiles, err := FindGeneratedFiles(root, []*tasks.APScope{scope})
	if err != nil {
		t.Fatal(err)
	}
	hasWorkflow := false
	for _, gf := range genFiles {
		if strings.Contains(gf.Path, "ap-test") {
			t.Fatalf("expected unmarked v1 presubmit script ap-test to not be marked generated, but found: %s", gf.Path)
		}
		if strings.Contains(gf.Path, "ci-presubmits.yaml") {
			hasWorkflow = true
		}
	}
	if !hasWorkflow {
		t.Fatalf("expected v1 workflow with 'Generated by' header to be detected as generated")
	}

	tasksToRun := []tasks.Task{
		&BuiltinGeneratorTask{
			Name:    "ap-test",
			RunFunc: runApTestGenerator,
		},
		&BuiltinGeneratorTask{
			Name: "github-actions",
			RunFunc: func(ctx context.Context, repoRoot string) error {
				return runGithubActionsGenerator(ctx, repoRoot, []*tasks.APScope{scope})
			},
		},
	}

	err = RunVerify(ctx, root, []*tasks.APScope{scope}, tasksToRun, false)
	if err != nil {
		t.Fatalf("RunVerify failed on v1 repo: %v", err)
	}
}
