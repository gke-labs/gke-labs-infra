type perturbedFile struct {
	path     string
	relPath  string
	hash     string
	modTime  time.Time
	mode     os.FileMode
	marker   string
	isBinary bool
	wasEmpty bool
	file     *repo.File
}

// FindGeneratedFiles discovers all generated files in the repository.
// A file is detected as generated by its header (ideally) or failing that by its name.
func FindGeneratedFiles(repoRoot string, scopes []*tasks.APScope) ([]*repo.File, error) {
	rootCfg, err := config.LoadAPConfig(repoRoot)
	if err != nil {
		return nil, err
	}

	var rootIgnorePatterns []string
	if rootCfg != nil && rootCfg.Generate != nil {
		rootIgnorePatterns = rootCfg.Generate.IgnoreOrphans
	}
	rootIgnoreList := repo.NewIgnoreList(rootIgnorePatterns)

	var generatedFiles []*repo.File
	seen := make(map[string]bool)

	for _, scope := range scopes {
		r, err := scope.GetRepo()
		if err != nil {
			return nil, err
		}

		scopeCfg, err := config.LoadAPConfig(scope.Dir)
		if err != nil {
			return nil, err
		}
		var scopeIgnorePatterns []string
		if scopeCfg != nil && scopeCfg.Generate != nil {
			scopeIgnorePatterns = scopeCfg.Generate.IgnoreOrphans
		}
		scopeIgnoreList := repo.NewIgnoreList(scopeIgnorePatterns)

		for _, f := range r.Files() {
			if seen[f.Path] {
				continue
			}
			seen[f.Path] = true

			// Skip testdata and test files
			if strings.Contains(f.RelPath, "/testdata/") || strings.HasPrefix(f.RelPath, "testdata/") {
				continue
			}
			if f.IsTest() {
				continue
			}

			// A file is generated because it says so in its header
			if !f.IsGenerated() {
				continue
			}

			// Check if ignored in root or scope config
			relToRoot, errRoot := filepath.Rel(repoRoot, f.Path)
			relToScope, errScope := filepath.Rel(scope.Dir, f.Path)

			ignored := false
			if errRoot == nil && rootIgnoreList.ShouldIgnore(filepath.ToSlash(relToRoot), false) {
				ignored = true
			}
			if !ignored && errScope == nil && scopeIgnoreList.ShouldIgnore(filepath.ToSlash(relToScope), false) {
				ignored = true
			}

			if !ignored {
				generatedFiles = append(generatedFiles, f)
			}
		}
	}

	sort.Slice(generatedFiles, func(i, j int) bool {
		return generatedFiles[i].Path < generatedFiles[j].Path
	})
	return generatedFiles, nil
}

// CommentSyntax returns the comment prefix and suffix for a file based on its
// path, extension, base name, or shebang. ok is true if the file format supports
// comments; false for binary files, uncommentable text (e.g. JSON, go.sum), or unknown formats.
func CommentSyntax(path string, data []byte) (prefix, suffix string, ok bool) {
	checkLen := len(data)
	if checkLen > 8000 {
		checkLen = 8000
	}
	if bytes.IndexByte(data[:checkLen], 0) != -1 {
		return "", "", false
	}

	ext := strings.ToLower(filepath.Ext(path))
	base := strings.ToLower(filepath.Base(path))

	if bytes.HasPrefix(data, []byte("#!")) {
		return "#", "", true
	}

	switch ext {
	case ".go", ".proto", ".c", ".cc", ".cpp", ".cxx", ".h", ".hpp", ".cs", ".java", ".js", ".jsx", ".ts", ".tsx", ".rs":
		return "//", "", true
	case ".yaml", ".yml", ".sh", ".bash", ".py", ".dockerfile", ".toml", ".rb":
		return "#", "", true
	case ".md", ".markdown", ".html", ".htm", ".xml", ".svg":
		return "<!--", " -->", true
	case ".sql", ".lua":
		return "--", "", true
	default:
		if base == "dockerfile" || strings.HasPrefix(base, "dockerfile.") || strings.HasSuffix(base, ".dockerfile") {
			return "#", "", true
		}
		if base == "makefile" || base == "gnumakefile" || strings.HasSuffix(base, ".mk") {
			return "#", "", true
		}
		if base == "go.mod" {
			return "//", "", true
		}
		return "", "", false
	}
}

// Perturb appends an undoable marker line to a text file, or flips the trailing byte of a binary file.
func Perturb(path string, data []byte, nonce string) (perturbed []byte, marker string, isBinary bool, wasEmpty bool) {
	if len(data) == 0 {
		return []byte{0x00}, "", true, true
	}

	prefix, suffix, ok := CommentSyntax(path, data)
	if !ok {
		// Binary file or uncommentable format: flip last byte
		perturbed = bytes.Clone(data)
		perturbed[len(perturbed)-1] ^= 0x01
		return perturbed, "", true, false
	}

	if suffix != "" {
		marker = fmt.Sprintf("\n%s ap-verify %s%s\n", prefix, nonce, suffix)
	} else {
		marker = fmt.Sprintf("\n%s ap-verify %s\n", prefix, nonce)
	}

	perturbed = append(bytes.Clone(data), []byte(marker)...)
	return perturbed, marker, false, false
}

// Undo reverses the perturbation applied by Perturb.
func Undo(data []byte, marker string, isBinary bool, wasEmpty bool) ([]byte, bool) {
	if wasEmpty {
		return nil, true
	}
	if isBinary {
		if len(data) == 0 {
			return nil, false
		}
		undone := bytes.Clone(data)
		undone[len(undone)-1] ^= 0x01
		return undone, true
	}

	if marker != "" && bytes.HasSuffix(data, []byte(marker)) {
		return bytes.TrimSuffix(data, []byte(marker)), true
	}
	return data, false
}

// RunVerify executes generator verification by perturbing all detected generated files,
// running generation tasks, and asserting that all perturbed files are restored byte-identically.
func RunVerify(ctx context.Context, repoRoot string, scopes []*tasks.APScope, allTasks []tasks.Task, dryRun bool) error {
	var r *repo.Repo
	if len(scopes) > 0 {
		var scopeRepoErr error
		r, scopeRepoErr = scopes[0].GetRepo()
		if scopeRepoErr != nil {
			return fmt.Errorf("failed to get repo from scope: %w", scopeRepoErr)
		}
	}
	if r == nil {
		var repoOpenErr error
		r, repoOpenErr = repo.Open(repoRoot)
		if repoOpenErr != nil {
			return fmt.Errorf("failed to open repo at %s: %w", repoRoot, repoOpenErr)
		}
	}

	generatedFiles, err := FindGeneratedFiles(repoRoot, scopes)
	if err != nil {
		return fmt.Errorf("failed to scan for generated files: %w", err)
	}

	var findings []string

	// Check for stale markers before run
	for _, f := range generatedFiles {
		data, err := os.ReadFile(f.Path)
		if err != nil {
			continue
		}
		if bytes.Contains(data, []byte("ap-verify ")) {
			rel, relErr := filepath.Rel(repoRoot, f.Path)
			if relErr != nil {
				rel = f.Path
			}
			findings = append(findings, fmt.Sprintf("file %q already contains a stale ap-verify marker before verification", filepath.ToSlash(rel)))
		}
	}

	// Capture initial git status
	initialGitStatus, gitErr := getGitStatus(ctx, repoRoot)
	if gitErr != nil {
		klog.V(2).Infof("failed to get initial git status: %v", gitErr)
	}

	// Generate nonce for this run
	nonceBytes := make([]byte, 8)
	if _, err := rand.Read(nonceBytes); err != nil {
		return fmt.Errorf("failed to generate nonce: %w", err)
	}
	nonce := hex.EncodeToString(nonceBytes)

	// In dry-run mode, report planned actions and don't mutate filesystem
	if dryRun {
		fmt.Printf("[dry-run] Generator verification would verify %d generated file(s):\n", len(generatedFiles))
		for _, f := range generatedFiles {
			rel, relErr := filepath.Rel(repoRoot, f.Path)
			if relErr != nil {
				rel = f.Path
			}
			fmt.Printf("  - %s\n", filepath.ToSlash(rel))
		}
		return tasks.Run(ctx, &tasks.APScope{RepoRoot: repoRoot, Dir: repoRoot, Repo: r}, allTasks, tasks.RunOptions{DryRun: true})
	}

	// Perturb each generated file that exists on disk, recording pre-run hash and mtime
	var perturbedFiles []*perturbedFile
	for _, f := range generatedFiles {
		info, err := os.Stat(f.Path)
		if err != nil {
			if os.IsNotExist(err) {
				continue
			}
			return fmt.Errorf("failed to stat %s: %w", f.Path, err)
		}

		data, err := os.ReadFile(f.Path)
		if err != nil {
			return fmt.Errorf("failed to read %s: %w", f.Path, err)
		}

		rel, relErr := filepath.Rel(repoRoot, f.Path)
		if relErr != nil {
			rel = f.Path
		}

		preHash, err := f.Hash()
		if err != nil {
			return fmt.Errorf("failed to hash %s: %w", f.Path, err)
		}

		perturbed, marker, isBinary, wasEmpty := Perturb(f.Path, data, nonce)

		pf := &perturbedFile{
			path:     f.Path,
			relPath:  filepath.ToSlash(rel),
			hash:     preHash,
			modTime:  info.ModTime(),
			mode:     info.Mode(),
			marker:   marker,
			isBinary: isBinary,
			wasEmpty: wasEmpty,
			file:     f,
		}
		perturbedFiles = append(perturbedFiles, pf)

		if err := r.WriteFile(f.Path, perturbed, info.Mode()); err != nil {
			return fmt.Errorf("failed to write perturbed file %s: %w", f.Path, err)
		}
	}

	// Defer cleanup: on failure or signal, restore perturbed files by stripping marker
	var success bool
	restoreAll := func() {
		for _, pf := range perturbedFiles {
			currentData, err := os.ReadFile(pf.path)
			if err != nil {
				continue
			}
			undone, ok := Undo(currentData, pf.marker, pf.isBinary, pf.wasEmpty)
			if ok {
				if err := r.WriteFile(pf.path, undone, pf.mode); err != nil {
					klog.Errorf("failed to restore file %s: %v", pf.path, err)
				}
			}
			if err := os.Chtimes(pf.path, pf.modTime, pf.modTime); err != nil {
				klog.V(2).Infof("failed to restore mtime for %s: %v", pf.path, err)
			}
		}
	}
	defer func() {
		if !success {
			restoreAll()
		}
	}()

	sigCh := make(chan os.Signal, 1)
	signal.Notify(sigCh, os.Interrupt, syscall.SIGTERM)
	defer signal.Stop(sigCh)
	go func() {
		select {
		case <-sigCh:
			restoreAll()
			os.Exit(130)
		case <-ctx.Done():
		}
	}()

	// Run generation tasks
	runErr := tasks.Run(ctx, &tasks.APScope{RepoRoot: repoRoot, Dir: repoRoot, Repo: r}, allTasks, tasks.RunOptions{DryRun: false})
	if runErr != nil {
		findings = append(findings, fmt.Sprintf("generation tasks failed: %v", runErr))
	}

	// Verify all perturbed files were restored byte-identical using content hashes
	for _, pf := range perturbedFiles {
		currentHash, err := pf.file.Hash()
		if err != nil {
			findings = append(findings, fmt.Sprintf("file %q missing after generation: %v", pf.relPath, err))
			continue
		}

		if currentHash == pf.hash {
			// File is byte-identical! Restore mtime.
			if err := os.Chtimes(pf.path, pf.modTime, pf.modTime); err != nil {
				klog.V(2).Infof("failed to restore mtime for %s: %v", pf.path, err)
			}
		} else {
			currentContent, readErr := os.ReadFile(pf.path)
			if readErr != nil {
				findings = append(findings, fmt.Sprintf("failed to read file %q: %v", pf.relPath, readErr))
			} else if !pf.isBinary && pf.marker != "" && bytes.Contains(currentContent, []byte(pf.marker)) {
				findings = append(findings, fmt.Sprintf("file %q was not regenerated (still carries perturbation marker)", pf.relPath))
			} else if pf.isBinary && len(currentContent) > 0 && pf.marker == "" && !pf.wasEmpty {
				findings = append(findings, fmt.Sprintf("file %q was not regenerated (still carries perturbation mutation)", pf.relPath))
			} else {
				findings = append(findings, fmt.Sprintf("file %q was modified by generation but differs from pre-run content", pf.relPath))
			}
		}
	}

	// Clean tree check: ensure generation did not produce any unexpected changes compared to pre-run
	currentGitStatus, curGitErr := getGitStatus(ctx, repoRoot)
	if curGitErr != nil {
		findings = append(findings, fmt.Sprintf("failed to get git status after generation: %v", curGitErr))
	} else if currentGitStatus != initialGitStatus {
		findings = append(findings, fmt.Sprintf("working tree was dirtied by generation:\n%s", currentGitStatus))
	}

	if len(findings) > 0 {
		var sb strings.Builder
		sb.WriteString("verify-generate failed:\n")
		for _, f := range findings {
			sb.WriteString("  - ")
			sb.WriteString(f)
			sb.WriteString("\n")
		}
		apCmd, err := GetApCommand(repoRoot, repoRoot)
		if err != nil {
			apCmd = "go run github.com/gke-labs/gke-labs-infra/ap@latest"
		}
		sb.WriteString(fmt.Sprintf("\nRun '%s generate //...' and commit the result.\n", apCmd))
		return errors.New(sb.String())
	}

	success = true
	klog.Infof("Generator verification passed: %d generated files verified", len(perturbedFiles))
	return nil
}

func getGitStatus(ctx context.Context, repoRoot string) (string, error) {
	checkCmd := exec.CommandContext(ctx, "git", "rev-parse", "--is-inside-work-tree")
	checkCmd.Dir = repoRoot
	if err := checkCmd.Run(); err != nil {
		// Not inside a git repository (e.g. temporary directory in tests)
		return "", nil
	}

	cmd := exec.CommandContext(ctx, "git", "status", "--porcelain")
	cmd.Dir = repoRoot
	out, err := cmd.Output()
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(out)), nil
}
