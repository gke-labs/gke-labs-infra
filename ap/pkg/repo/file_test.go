func TestIsGeneratedLine(t *testing.T) {
	tests := []struct {
		name        string
		line        string
		expected    bool
		cleanPrefix string
	}{
		{
			name:        "Go comment standard",
			line:        "// Code generated by protoc-gen-go. DO NOT EDIT.",
			expected:    true,
			cleanPrefix: "Code generated by protoc-gen-go. DO NOT EDIT.",
		},
		{
			name:        "Shell comment standard",
			line:        "# Code generated by ap generate. DO NOT EDIT.",
			expected:    true,
			cleanPrefix: "Code generated by ap generate. DO NOT EDIT.",
		},
		{
			name:        "YAML comment",
			line:        "# Code generated by tool. DO NOT EDIT.",
			expected:    true,
			cleanPrefix: "Code generated by tool. DO NOT EDIT.",
		},
		{
			name:        "HTML comment",
			line:        "<!-- Code generated by markdown-gen. DO NOT EDIT. -->",
			expected:    true,
			cleanPrefix: "Code generated by markdown-gen. DO NOT EDIT.",
		},
		{
			name:        "SQL comment",
			line:        "-- Code generated by sqlc. DO NOT EDIT.",
			expected:    true,
			cleanPrefix: "Code generated by sqlc. DO NOT EDIT.",
		},
		{
			name:        "C block comment",
			line:        "/* Code generated by c-tool. DO NOT EDIT. */",
			expected:    true,
			cleanPrefix: "Code generated by c-tool. DO NOT EDIT.",
		},
		{
			name:        "Pre-#487 shell header",
			line:        "# Generated by ap generate. DO NOT EDIT.",
			expected:    true,
			cleanPrefix: "Generated by ap generate. DO NOT EDIT.",
		},
		{
			name:        "Pre-#487 Go header",
			line:        "// Generated by custom tool. DO NOT EDIT.",
			expected:    true,
			cleanPrefix: "Generated by custom tool. DO NOT EDIT.",
		},
		{
			name:     "DO NOT EDIT without Code generated",
			line:     "// DO NOT EDIT this file manually",
			expected: false,
		},
		{
			name:     "Regular code comment",
			line:     "// This is a normal comment",
			expected: false,
		},
		{
			name:     "Empty line",
			line:     "",
			expected: false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, clean := IsGeneratedLine(tt.line)
			if got != tt.expected {
				t.Errorf("IsGeneratedLine(%q) = %v, want %v", tt.line, got, tt.expected)
			}
			if tt.expected && clean != tt.cleanPrefix {
				t.Errorf("IsGeneratedLine(%q) clean = %q, want %q", tt.line, clean, tt.cleanPrefix)
			}
		})
	}
}

func TestFile_IsGenerated(t *testing.T) {
	tempDir := t.TempDir()

	// 1. Valid generated Go file
	goPath := filepath.Join(tempDir, "gen.go")
	if err := os.WriteFile(goPath, []byte("// Code generated by test. DO NOT EDIT.\npackage p\n"), 0644); err != nil {
		t.Fatal(err)
	}
	fGo := &File{Path: goPath, Name: "gen.go"}
	if !fGo.IsGenerated() {
		t.Errorf("expected gen.go to be generated")
	}

	// 2. Valid generated shell script
	shPath := filepath.Join(tempDir, "script.sh")
	if err := os.WriteFile(shPath, []byte("#!/bin/bash\n# Code generated by ap generate. DO NOT EDIT.\necho 1\n"), 0755); err != nil {
		t.Fatal(err)
	}
	fSh := &File{Path: shPath, Name: "script.sh"}
	if !fSh.IsGenerated() {
		t.Errorf("expected script.sh to be generated")
	}
	if !strings.Contains(fSh.GeneratedHeader(), "by ap generate") {
		t.Errorf("expected header to contain 'by ap generate', got %q", fSh.GeneratedHeader())
	}

	// 3. Header past line 30 (should NOT be detected as generated)
	var sb strings.Builder
	for i := 0; i < 35; i++ {
		sb.WriteString(fmt.Sprintf("// line %d\n", i))
	}
	sb.WriteString("// Code generated by late. DO NOT EDIT.\npackage p\n")
	latePath := filepath.Join(tempDir, "late.go")
	if err := os.WriteFile(latePath, []byte(sb.String()), 0644); err != nil {
		t.Fatal(err)
	}
	fLate := &File{Path: latePath, Name: "late.go"}
	if fLate.IsGenerated() {
		t.Errorf("header past line 30 should not be recognized as generated")
	}
}

func TestFile_HashAndRefresh(t *testing.T) {
	tempDir := t.TempDir()
	filePath := filepath.Join(tempDir, "sample.txt")
	if err := os.WriteFile(filePath, []byte("version 1"), 0644); err != nil {
		t.Fatal(err)
	}

	f := &File{Path: filePath, Name: "sample.txt"}

	hash1, err := f.Hash()
	if err != nil {
		t.Fatalf("f.Hash() failed: %v", err)
	}
	if hash1 == "" {
		t.Fatalf("expected non-empty hash")
	}

	// Second call should return the exact same memoized hash
	hash2, err := f.Hash()
	if err != nil {
		t.Fatalf("second f.Hash() failed: %v", err)
	}
	if hash1 != hash2 {
		t.Errorf("expected memoized hash to match, got %q vs %q", hash1, hash2)
	}

	// Modify file
	if err := os.WriteFile(filePath, []byte("version 2 modified"), 0644); err != nil {
		t.Fatal(err)
	}

	// With staleness guard, Hash() re-stats and detects the modification automatically
	hash3, err := f.Hash()
	if err != nil {
		t.Fatalf("f.Hash() after modification failed: %v", err)
	}
	if hash3 == hash1 {
		t.Errorf("expected hash to update after file modification, got %q", hash3)
	}

	// After InvalidateCachedInfo, hash is recomputed and remains consistent
	f.InvalidateCachedInfo()
	hash4, err := f.Hash()
	if err != nil {
		t.Fatalf("f.Hash() after InvalidateCachedInfo failed: %v", err)
	}
	if hash4 != hash3 {
		t.Errorf("expected hash after refresh to match %q, got %q", hash3, hash4)
	}
}

func TestFile_HasGoGenerate(t *testing.T) {
	tempDir := t.TempDir()

	// 1. Go file with //go:generate
	genPath := filepath.Join(tempDir, "has_gen.go")
	if err := os.WriteFile(genPath, []byte("package p\n//go:generate echo 1\n"), 0644); err != nil {
		t.Fatal(err)
	}
	f1 := &File{Path: genPath, Name: "has_gen.go"}
	if !f1.HasGoGenerate() {
		t.Errorf("expected has_gen.go to have //go:generate")
	}

	// 2. Go file without //go:generate
	noGenPath := filepath.Join(tempDir, "no_gen.go")
	if err := os.WriteFile(noGenPath, []byte("package p\n// regular comment\n"), 0644); err != nil {
		t.Fatal(err)
	}
	f2 := &File{Path: noGenPath, Name: "no_gen.go"}
	if f2.HasGoGenerate() {
		t.Errorf("no_gen.go should not have //go:generate")
	}

	// 3. Non-Go file with //go:generate
	txtPath := filepath.Join(tempDir, "file.txt")
	if err := os.WriteFile(txtPath, []byte("//go:generate echo 1\n"), 0644); err != nil {
		t.Fatal(err)
	}
	f3 := &File{Path: txtPath, Name: "file.txt"}
	if f3.HasGoGenerate() {
		t.Errorf("non-Go file should not report HasGoGenerate")
	}
}

func TestFile_ReferencedGOOS(t *testing.T) {
	tempDir := t.TempDir()

	tests := []struct {
		name     string
		fileName string
		content  string
		want     []string
	}{
		{
			name:     "plain file",
			fileName: "main.go",
			content:  "package main\n\nfunc main() {}\n",
			want:     nil,
		},
		{
			name:     "filename suffix linux",
			fileName: "foo_linux.go",
			content:  "package foo\n",
			want:     []string{"linux"},
		},
		{
			name:     "filename suffix _linux.go",
			fileName: "_linux.go",
			content:  "package foo\n",
			want:     []string{"linux"},
		},
		{
			name:     "filename suffix linux amd64",
			fileName: "foo_linux_amd64.go",
			content:  "package foo\n",
			want:     []string{"linux"},
		},
		{
			name:     "filename suffix linux test",
			fileName: "foo_linux_test.go",
			content:  "package foo\n",
			want:     []string{"linux"},
		},
		{
			name:     "linux.go without preceding underscore is not OS specific",
			fileName: "linux.go",
			content:  "package linux\n",
			want:     nil,
		},
		{
			name:     "go build directive with multiple OS tags",
			fileName: "cross.go",
			content:  "//go:build (darwin || linux) && !windows\n\npackage cross\n",
			want:     []string{"darwin", "linux", "windows"},
		},
		{
			name:     "filename suffix and build directive combined and deduplicated",
			fileName: "bar_darwin.go",
			content:  "//go:build darwin || freebsd\n\npackage bar\n",
			want:     []string{"darwin", "freebsd"},
		},
		{
			name:     "non-go file ignored",
			fileName: "foo_linux.txt",
			content:  "hello",
			want:     nil,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			filePath := filepath.Join(tempDir, tt.fileName)
			if err := os.WriteFile(filePath, []byte(tt.content), 0644); err != nil {
				t.Fatal(err)
			}
			f := &File{Path: filePath, Name: tt.fileName}
			got := f.ReferencedGOOS()
			if !reflect.DeepEqual(got, tt.want) {
				t.Errorf("ReferencedGOOS() = %v, want %v", got, tt.want)
			}

			// Verify memoization
			got2 := f.ReferencedGOOS()
			if !reflect.DeepEqual(got2, tt.want) {
				t.Errorf("memoized ReferencedGOOS() = %v, want %v", got2, tt.want)
			}

			// Verify InvalidateCachedInfo()
			f.InvalidateCachedInfo()
			got3 := f.ReferencedGOOS()
			if !reflect.DeepEqual(got3, tt.want) {
				t.Errorf("refreshed ReferencedGOOS() = %v, want %v", got3, tt.want)
			}
		})
	}
}
